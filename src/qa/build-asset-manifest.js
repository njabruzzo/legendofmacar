'use strict';
/**
 * Write src/assets/asset-manifest.js from the files under assets/.
 * Run: node src/qa/build-asset-manifest.js
 * The test src/qa/AssetManifest.test.js fails if the committed list drifts.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '../..');
const out = path.join(root, 'src/assets/asset-manifest.js');

function walk(dir, acc) {
  for (const ent of fs.readdirSync(dir, {withFileTypes: true})) {
    const p = path.join(dir, ent.name);
    if (ent.isDirectory()) walk(p, acc);
    else if (ent.isFile()) acc.push(path.relative(root, p).split(path.sep).join('/'));
  }
  return acc;
}

function build() {
  const files = walk(path.join(root, 'assets'), []).sort();
  const lines = files.map(f => '  ' + JSON.stringify(f) + ':1');
  const body = [
    '/* Generated by node src/qa/build-asset-manifest.js',
    '   Every file under assets/, keyed by repo-relative path.',
    '   index.html drops sprite keys that are not in this list',
    '   so the loader never requests a file that is not on disk. */',
    'var ASSET_FILES={',
    lines.join(',\n'),
    '};',
    ''
  ].join('\n');
  return {files, body};
}

if (require.main === module) {
  const {files, body} = build();
  fs.mkdirSync(path.dirname(out), {recursive: true});
  fs.writeFileSync(out, body);
  console.log('wrote ' + files.length + ' paths to ' + path.relative(root, out));
}

module.exports = {walk, build, root, out};
